import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import path from 'node:path';
import os from 'node:os';
import { createHash } from 'node:crypto';
import { createServer } from 'node:http';
import { _electron as electron } from 'playwright-core';

const repository = path.resolve(import.meta.dirname, '../..');
const installedApp = process.env.MESNIER_INSTALLED_APP;
const evidence = path.resolve(process.env.MESNIER_UI_EVIDENCE ?? path.join(repository, '.evidence', `settings-board-${Date.now()}`));
const hash = async (file) => createHash('sha256').update(await fs.readFile(file)).digest('hex');

test('分类设置与通高看板真实 Electron 验收', { timeout: 120_000 }, async () => {
  const data = path.join(evidence, 'data'); const launch = path.join(evidence, 'app');
  await fs.mkdir(data, { recursive: true }); await fs.mkdir(launch, { recursive: true });
  await fs.cp(path.join(repository, 'dist'), path.join(launch, 'dist'), { recursive: true });
  await fs.copyFile(path.join(repository, 'package.json'), path.join(launch, 'package.json'));
  const work = await fs.mkdtemp(path.join(os.tmpdir(), 'mesnier-layout-'));
  const at = (hours) => new Date(Date.now() - hours * 3600_000).toISOString();
  const project = { id: 'mesnier', name: 'Mesnier', path: work, createdAt: at(100) };
  const titles = ['梳理桌面工作台的界面与交互规范', '补充模型配置的连接验证', '完善任务状态与验收记录', '准备发布说明与安装检查', '核对深色外观与最小窗口布局'];
  const tasks = Array.from({ length: 27 }, (_, i) => ({ id: `task-${String(i).padStart(5, '0')}`, projectId: project.id, sessionId: `session-${i}`, title: titles[i % titles.length] + (i > 4 ? ` · ${i + 1}` : ''), description: '按既定范围检查界面行为，并记录实际验证证据。', acceptanceCriteria: '', status: i < 21 ? 'todo' : i < 24 ? 'in_progress' : 'review', agentId: i % 2 ? 'coding' : 'general', createdAt: at(100), updatedAt: at(i + 1) }));
  const sessions = tasks.map((task) => ({ id: task.sessionId, projectId: project.id, title: task.title, createdAt: task.createdAt, updatedAt: task.updatedAt }));
  // 合成记录只用于布局、筛选与身份验证；真实执行另由工作流套件验证。
  const state = { schemaVersion: 1, revision: 1, projects: [project], sessions, tasks, runs: [], messages: [], events: [], approvals: [], artifacts: [], models: [], agents: [{ id: 'general', name: '通用助手', instructions: '' }, { id: 'coding', name: '开发助手', instructions: '' }], runtime: {}, app: {} };
  await fs.writeFile(path.join(data, 'state.json'), JSON.stringify(state));
  let releaseResponse;
  let requestCount = 0;
  const server = createServer(async (request, response) => {
    for await (const _ of request) { /* 消耗受控请求，不记录密钥或正文。 */ }
    requestCount++;
    await new Promise((resolve) => { releaseResponse = resolve; });
    response.writeHead(503, { 'content-type': 'application/json' }); response.end(JSON.stringify({ error: { message: '受控服务暂时不可用' } }));
  });
  await new Promise((resolve) => server.listen(0, '127.0.0.1', resolve));
  const report = { passed: false, checks: [], screenshots: [], pageErrors: [], sourceHashes: {}, buildHashes: {} };
  for (const file of ['apps/desktop/src/renderer/components/Settings.tsx', 'apps/desktop/src/renderer/components/Board.tsx', 'apps/desktop/src/renderer/components/ui.tsx', 'apps/desktop/src/renderer/styles.css', 'tests/ui/settings-board.test.mjs']) report.sourceHashes[file] = await hash(path.join(repository, file));
  for (const file of await fs.readdir(path.join(launch, 'dist/renderer/assets'))) report.buildHashes[file] = await hash(path.join(launch, 'dist/renderer/assets', file));
  let app; let page; let failure;
  const snapshot = () => page.evaluate(() => window.mesnier.getSnapshot());
  const shot = async (name) => { await page.screenshot({ path: path.join(evidence, `${name}.png`), animations: 'disabled', scale: 'css' }); report.screenshots.push(name); };
  try {
    const executablePath = installedApp ? path.join(installedApp, 'Contents/MacOS/Mesnier') : path.join(repository, 'node_modules/electron/dist/Electron.app/Contents/MacOS/Electron');
    app = await electron.launch({ executablePath, args: installedApp ? [] : [launch], cwd: launch, env: { ...process.env, MESNIER_HOME: data }, timeout: 30000 });
    page = await app.firstWindow(); page.setDefaultTimeout(10000); page.on('pageerror', (error) => report.pageErrors.push(error.message));
    report.application = await app.evaluate(({ app }) => ({ packaged: app.isPackaged, version: app.getVersion(), executable: app.getPath('exe') }));
    if (installedApp) { assert.equal(report.application.packaged, true); report.asarHash = await hash(path.join(installedApp, 'Contents/Resources/app.asar')); }
    await page.locator('.shell').waitFor();
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 930));
    await page.getByLabel('消息输入').fill('从设置返回后保留这份草稿。');
    await page.getByRole('button', { name: '设置与模型' }).click();
    const settings = page.getByRole('dialog', { name: '工作台设置' });
    assert.equal((await settings.boundingBox()).width, 1440);
    assert.equal((await settings.locator('.settings-nav').boundingBox()).width, 268);
    await shot('01-settings-empty-light');
    await settings.getByLabel('配置名称').fill('工作模型');
    await settings.getByLabel('模型名称').fill('local-fixture');
    await settings.getByLabel('API 地址').fill(`http://127.0.0.1:${server.address().port}/v1`);
    await settings.getByLabel('上下文长度').fill('200000');
    await settings.getByRole('button', { name: '外观', exact: true }).click();
    await settings.getByRole('button', { name: '深色', exact: true }).click();
    await shot('02-appearance-dark');
    await settings.getByRole('button', { name: '关于 Mesnier', exact: true }).click();
    await shot('03-about-dark');
    await settings.getByRole('button', { name: '模型服务', exact: true }).click();
    assert.equal(await settings.getByLabel('配置名称').inputValue(), '工作模型');
    await settings.getByRole('button', { name: '返回工作台' }).click();
    const confirm = page.getByRole('dialog', { name: '放弃未保存的修改？' });
    await confirm.waitFor();
    await page.keyboard.press('Shift+Tab');
    assert.equal(await confirm.evaluate((element) => element.contains(document.activeElement)), true);
    await page.keyboard.press('Escape');
    await confirm.waitFor({ state: 'detached' });
    assert.equal(await settings.getByLabel('配置名称').inputValue(), '工作模型');
    await settings.getByRole('button', { name: '保存配置', exact: true }).click();
    await page.waitForFunction(async () => (await window.mesnier.getSnapshot()).models.length === 1);
    await settings.getByRole('button', { name: '新增', exact: true }).click();
    await settings.getByLabel('配置名称').fill('未保存草稿');
    await settings.getByRole('button', { name: '编辑模型 工作模型' }).click();
    await confirm.getByRole('button', { name: '放弃修改', exact: true }).click();
    assert.equal(await settings.getByLabel('配置名称').inputValue(), '工作模型');
    report.checks.push('分类切换保留草稿；关闭及切换模型确认放弃；嵌套Escape与Tab只作用于顶层');
    await settings.getByRole('button', { name: '保存并验证', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.model-save-actions button:last-child')?.disabled);
    assert.equal(await settings.getByRole('button', { name: '返回工作台' }).isDisabled(), true);
    assert.equal(await settings.getByRole('button', { name: '外观', exact: true }).isDisabled(), true);
    await page.keyboard.press('Escape'); assert.equal(await settings.count(), 1);
    await shot('04-settings-pending-dark');
    for (let i = 0; i < 100 && !releaseResponse; i++) await new Promise((resolve) => setTimeout(resolve, 30));
    assert.equal(requestCount, 1); releaseResponse();
    await page.waitForFunction(() => document.querySelector('.model-save-actions button:last-child')?.disabled === false);
    assert.match(await settings.locator('[role="status"]').textContent(), /503|不可用|失败/);
    await shot('05-settings-error-dark');
    report.checks.push('保存中禁用导航和关闭，受控503连接失败如实显示，不启动执行');
    await settings.getByRole('button', { name: '外观', exact: true }).click();
    await settings.getByRole('button', { name: '浅色', exact: true }).click();
    await shot('06-appearance-light');
    await settings.getByRole('button', { name: '模型服务', exact: true }).click();
    await settings.getByRole('button', { name: '保存配置', exact: true }).click();
    await page.waitForFunction(() => document.querySelector('.model-fields [role="status"]')?.textContent?.includes('已保存'));
    await shot('07-settings-model-light');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 700));
    await page.waitForFunction(() => innerWidth === 1000);
    assert.equal((await settings.locator('.settings-nav').boundingBox()).width, 68);
    await settings.locator('.model-fields').evaluate((element) => { element.scrollTop = element.scrollHeight; });
    const header = await settings.locator('.settings-frame-header').boundingBox();
    const save = await settings.getByRole('button', { name: '保存配置', exact: true }).boundingBox();
    assert.ok(header.y < 6 && save.y + save.height < 700);
    assert.equal(await settings.evaluate((element) => element.scrollWidth <= element.clientWidth), true);
    await shot('08-settings-minimum-light');
    await settings.getByRole('button', { name: '返回工作台' }).click();
    assert.equal(await page.getByLabel('消息输入').inputValue(), '从设置返回后保留这份草稿。');
    report.checks.push('1000×700图标导航，固定标题与保存按钮可访问；返回保留工作台草稿');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1440, 930));
    await page.getByRole('button', { name: '看板', exact: true }).click();
    const board = page.getByLabel('任务看板', { exact: true });
    const verifyColumns = async () => {
      const box = await board.boundingBox(); const cols = await board.locator('.board-column').all();
      assert.equal(cols.length, 4);
      for (const col of cols) { const rect = await col.boundingBox(); assert.equal(rect.width, 280); assert.ok(rect.height >= box.height - 30, '空列和有任务列均占满可用高度'); }
    };
    await verifyColumns(); await shot('09-board-light');
    const first = board.locator('.column-tasks').first(); const head = await board.locator('.column-heading').first().boundingBox();
    await first.evaluate((element) => { element.scrollTop = 250; });
    assert.ok(await first.evaluate((element) => element.scrollTop) > 200);
    assert.equal((await board.locator('.column-heading').first().boundingBox()).y, head.y);
    assert.equal(await board.locator('.column-tasks').nth(1).evaluate((element) => element.scrollTop), 0);
    const broken = await page.addStyleTag({ content: '.board { align-items: start !important; } .board-column { height: 200px !important; }' });
    await assert.rejects(verifyColumns, /占满可用高度/);
    await broken.evaluate((element) => element.remove()); await verifyColumns();
    report.checks.push('四列280px通高，空列同高，各列独立滚动；故意恢复短列时几何断言失败');
    await page.getByRole('button', { name: '筛选', exact: true }).click();
    await page.getByLabel('按 Agent 筛选').selectOption('coding');
    assert.equal(await board.locator('.task-card').count(), tasks.filter((item) => item.agentId === 'coding').length);
    await page.getByLabel('按任务状态筛选').selectOption('review');
    assert.equal(await board.locator('.board-column').count(), 1);
    await page.keyboard.press('Escape');
    await page.getByRole('button', { name: '全部任务', exact: true }).click();
    await page.getByLabel('搜索任务', { exact: true }).fill('不存在的标题');
    assert.equal(await board.locator('.task-card').count(), 0);
    await shot('10-board-filter-empty');
    await page.getByRole('button', { name: '全部任务', exact: true }).click();
    await page.getByRole('button', { name: '显示', exact: true }).click();
    await page.getByLabel('任务摘要', { exact: true }).check();
    await page.getByLabel('项目标签', { exact: true }).uncheck();
    await page.getByLabel('更新时间', { exact: true }).uncheck();
    assert.equal(await board.locator('.task-card p').count(), 27);
    assert.equal(await board.locator('.task-project, time').count(), 0);
    await page.getByLabel('任务排序').selectOption('oldest');
    assert.equal(await board.locator('.task-card').first().getAttribute('data-task-id'), 'task-00020');
    await page.getByLabel('任务排序').selectOption('newest');
    await page.getByLabel('任务摘要', { exact: true }).uncheck();
    await page.getByLabel('项目标签', { exact: true }).check();
    await page.getByLabel('更新时间', { exact: true }).check();
    await page.keyboard.press('Escape');
    assert.deepEqual((await snapshot()).tasks, tasks); assert.equal((await snapshot()).runs.length, 0);
    report.checks.push('Agent/状态/搜索过滤、摘要/项目/时间显示及排序有效，任务和执行不被改变');
    await page.getByRole('button', { name: '切换深色外观' }).click();
    await shot('11-board-dark');
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setSize(1000, 700));
    await page.waitForFunction(() => innerWidth === 1000);
    await verifyColumns();
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
    await board.evaluate((element) => { element.scrollLeft = element.scrollWidth; });
    assert.ok(await board.evaluate((element) => element.scrollLeft) > 0);
    await shot('12-board-minimum-dark');
    await board.evaluate((element) => { element.scrollLeft = 0; });
    await board.locator('.task-card').first().click();
    await page.getByRole('button', { name: '进入对话', exact: true }).click();
    assert.equal(await page.getByLabel('消息输入').inputValue(), '从设置返回后保留这份草稿。');
    report.checks.push('1000×700横向滚动、详情和关联对话正常，深浅主题与长列表截图已保存');
    assert.deepEqual(report.pageErrors, []); report.passed = true;
  } catch (error) { failure = error; report.error = error.message; await shot('failure').catch(() => {}); }
  finally { releaseResponse?.(); await app?.close(); server.closeAllConnections(); await new Promise((resolve) => server.close(resolve)); await fs.rm(work, { recursive: true, force: true }); await fs.writeFile(path.join(evidence, 'report.json'), JSON.stringify(report, null, 2)); }
  if (failure) throw failure;
});
